/* ==============================================================================
 * SCRIPT 02: Tablas de Dominio y Comentarios DDL (Fase 1)
 * Esquema Owner: USR_DBTEST
 * Tablespaces: Datos -> TS_DBTEST_DAT | Índices/PKs -> TS_DBTEST_IDX
 * ============================================================================== */

ALTER SESSION SET CURRENT_SCHEMA = USR_DBTEST;

-- 1. TABLA CLIENTES
CREATE TABLE USR_DBTEST.CLIENTES (
    ID_CLIENTE       NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMBRE           VARCHAR2(100) NOT NULL,
    TIPO_CLIENTE     VARCHAR2(20) NOT NULL CHECK (TIPO_CLIENTE IN ('INDIVIDUAL', 'EMPRESA')),
    REGION           VARCHAR2(50) NOT NULL,
    PAIS             VARCHAR2(50) DEFAULT 'Argentina' NOT NULL,
    FECHA_ALTA       DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CLIENTES PRIMARY KEY (ID_CLIENTE) USING INDEX TABLESPACE TS_DBTEST_IDX
) TABLESPACE TS_DBTEST_DAT;

COMMENT ON TABLE USR_DBTEST.CLIENTES IS 'Tabla de catálogo de clientes individuales y corporativos';
COMMENT ON COLUMN USR_DBTEST.CLIENTES.ID_CLIENTE IS 'Identificador único autogenerado del cliente (PK)';
COMMENT ON COLUMN USR_DBTEST.CLIENTES.NOMBRE IS 'Nombre completo o razón social del cliente';
COMMENT ON COLUMN USR_DBTEST.CLIENTES.TIPO_CLIENTE IS 'Tipo de cliente: INDIVIDUAL o EMPRESA';
COMMENT ON COLUMN USR_DBTEST.CLIENTES.REGION IS 'Región geográfica comercial (ej. CABA, GBA, PAMPEANA)';
COMMENT ON COLUMN USR_DBTEST.CLIENTES.PAIS IS 'País de residencia comercial';
COMMENT ON COLUMN USR_DBTEST.CLIENTES.FECHA_ALTA IS 'Fecha de alta del cliente en el sistema';

-- 2. TABLA ITEMS
CREATE TABLE USR_DBTEST.ITEMS (
    ID_ITEM          NUMBER GENERATED ALWAYS AS IDENTITY,
    CODIGO           VARCHAR2(20) NOT NULL,
    NOMBRE           VARCHAR2(100) NOT NULL,
    TIPO_ITEM        VARCHAR2(20) NOT NULL CHECK (TIPO_ITEM IN ('PRODUCTO', 'SERVICIO')),
    CATEGORIA        VARCHAR2(50) NOT NULL,
    PRECIO_LISTA     NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_ITEMS PRIMARY KEY (ID_ITEM) USING INDEX TABLESPACE TS_DBTEST_IDX,
    CONSTRAINT UK_ITEMS_CODIGO UNIQUE (CODIGO) USING INDEX TABLESPACE TS_DBTEST_IDX
) TABLESPACE TS_DBTEST_DAT;

COMMENT ON TABLE USR_DBTEST.ITEMS IS 'Catálogo de productos y servicios comercializados';
COMMENT ON COLUMN USR_DBTEST.ITEMS.ID_ITEM IS 'Identificador único del item (PK)';
COMMENT ON COLUMN USR_DBTEST.ITEMS.CODIGO IS 'Código único comercial del producto o servicio';
COMMENT ON COLUMN USR_DBTEST.ITEMS.NOMBRE IS 'Nombre descriptivo del item';
COMMENT ON COLUMN USR_DBTEST.ITEMS.TIPO_ITEM IS 'Clasificación de tipo: PRODUCTO o SERVICIO';
COMMENT ON COLUMN USR_DBTEST.ITEMS.CATEGORIA IS 'Categoría de producto/servicio (ej. HARDWARE, CONSULTORIA, LICENCIAMIENTO)';
COMMENT ON COLUMN USR_DBTEST.ITEMS.PRECIO_LISTA IS 'Precio de lista unitario sin descuentos';

-- 3. TABLA CANALES_VENTA
CREATE TABLE USR_DBTEST.CANALES_VENTA (
    ID_CANAL         NUMBER GENERATED ALWAYS AS IDENTITY,
    NOMBRE_CANAL     VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_CANALES_VENTA PRIMARY KEY (ID_CANAL) USING INDEX TABLESPACE TS_DBTEST_IDX
) TABLESPACE TS_DBTEST_DAT;

COMMENT ON TABLE USR_DBTEST.CANALES_VENTA IS 'Catálogo de canales de venta comercial';
COMMENT ON COLUMN USR_DBTEST.CANALES_VENTA.ID_CANAL IS 'Identificador único del canal de venta (PK)';
COMMENT ON COLUMN USR_DBTEST.CANALES_VENTA.NOMBRE_CANAL IS 'Nombre del canal (ej. WEB, SUCURSAL, VENTA DIRECTA, PARTNER)';

-- 4. TABLA VENTAS
CREATE TABLE USR_DBTEST.VENTAS (
    ID_VENTA         NUMBER GENERATED ALWAYS AS IDENTITY,
    NUMERO_FACTURA   VARCHAR2(30) NOT NULL,
    ID_CLIENTE       NUMBER NOT NULL,
    ID_CANAL         NUMBER NOT NULL,
    FECHA_VENTA      DATE DEFAULT SYSDATE NOT NULL,
    ESTADO           VARCHAR2(20) DEFAULT 'COMPLETADA' NOT NULL CHECK (ESTADO IN ('COMPLETADA', 'ANULADA', 'PENDIENTE')),
    CONSTRAINT PK_VENTAS PRIMARY KEY (ID_VENTA) USING INDEX TABLESPACE TS_DBTEST_IDX,
    CONSTRAINT FK_VENTAS_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES USR_DBTEST.CLIENTES(ID_CLIENTE),
    CONSTRAINT FK_VENTAS_CANAL FOREIGN KEY (ID_CANAL) REFERENCES USR_DBTEST.CANALES_VENTA(ID_CANAL)
) TABLESPACE TS_DBTEST_DAT;

CREATE INDEX USR_DBTEST.IDX_VENTAS_CLIENTE ON USR_DBTEST.VENTAS(ID_CLIENTE) TABLESPACE TS_DBTEST_IDX;
CREATE INDEX USR_DBTEST.IDX_VENTAS_CANAL ON USR_DBTEST.VENTAS(ID_CANAL) TABLESPACE TS_DBTEST_IDX;
CREATE INDEX USR_DBTEST.IDX_VENTAS_FECHA ON USR_DBTEST.VENTAS(FECHA_VENTA) TABLESPACE TS_DBTEST_IDX;

COMMENT ON TABLE USR_DBTEST.VENTAS IS 'Cabecera de transacciones de venta de la compañía';
COMMENT ON COLUMN USR_DBTEST.VENTAS.ID_VENTA IS 'Identificador único de la transacción de venta (PK)';
COMMENT ON COLUMN USR_DBTEST.VENTAS.NUMERO_FACTURA IS 'Número comprobante o factura comercial';
COMMENT ON COLUMN USR_DBTEST.VENTAS.ID_CLIENTE IS 'Referencia al cliente (FK)';
COMMENT ON COLUMN USR_DBTEST.VENTAS.ID_CANAL IS 'Referencia al canal de venta (FK)';
COMMENT ON COLUMN USR_DBTEST.VENTAS.FECHA_VENTA IS 'Fecha y hora de emisión de la venta';
COMMENT ON COLUMN USR_DBTEST.VENTAS.ESTADO IS 'Estado de la venta: COMPLETADA, ANULADA o PENDIENTE';

-- 5. TABLA DETALLE_VENTA
CREATE TABLE USR_DBTEST.DETALLE_VENTA (
    ID_DETALLE       NUMBER GENERATED ALWAYS AS IDENTITY,
    ID_VENTA         NUMBER NOT NULL,
    ID_ITEM          NUMBER NOT NULL,
    CANTIDAD         NUMBER(8,2) NOT NULL,
    PRECIO_UNITARIO  NUMBER(12,2) NOT NULL,
    SUBTOTAL         NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_DETALLE_VENTA PRIMARY KEY (ID_DETALLE) USING INDEX TABLESPACE TS_DBTEST_IDX,
    CONSTRAINT FK_DETALLE_VENTA FOREIGN KEY (ID_VENTA) REFERENCES USR_DBTEST.VENTAS(ID_VENTA),
    CONSTRAINT FK_DETALLE_ITEM FOREIGN KEY (ID_ITEM) REFERENCES USR_DBTEST.ITEMS(ID_ITEM)
) TABLESPACE TS_DBTEST_DAT;

CREATE INDEX USR_DBTEST.IDX_DETALLE_VENTA ON USR_DBTEST.DETALLE_VENTA(ID_VENTA) TABLESPACE TS_DBTEST_IDX;
CREATE INDEX USR_DBTEST.IDX_DETALLE_ITEM ON USR_DBTEST.DETALLE_VENTA(ID_ITEM) TABLESPACE TS_DBTEST_IDX;

COMMENT ON TABLE USR_DBTEST.DETALLE_VENTA IS 'Líneas de detalle de ítems por transacción de venta';
COMMENT ON COLUMN USR_DBTEST.DETALLE_VENTA.ID_DETALLE IS 'Identificador único de la línea de detalle (PK)';
COMMENT ON COLUMN USR_DBTEST.DETALLE_VENTA.ID_VENTA IS 'Referencia a la cabecera de venta (FK)';
COMMENT ON COLUMN USR_DBTEST.DETALLE_VENTA.ID_ITEM IS 'Referencia al producto o servicio comercializado (FK)';
COMMENT ON COLUMN USR_DBTEST.DETALLE_VENTA.CANTIDAD IS 'Cantidad de unidades comercializadas';
COMMENT ON COLUMN USR_DBTEST.DETALLE_VENTA.PRECIO_UNITARIO IS 'Precio cobrado por unidad';
COMMENT ON COLUMN USR_DBTEST.DETALLE_VENTA.SUBTOTAL IS 'Monto subtotal cobrado (Cantidad * Precio Unitario)';

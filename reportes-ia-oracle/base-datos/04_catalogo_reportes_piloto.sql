ALTER SESSION SET CURRENT_SCHEMA = USR_DBTEST;

-- 1. CREACIÓN DE LA TABLA CATALOGO_REPORTES
CREATE TABLE USR_DBTEST.CATALOGO_REPORTES (
    ID_REPORTE          NUMBER GENERATED ALWAYS AS IDENTITY,
    CATEGORIA           VARCHAR2(100) NOT NULL,
    NOMBRE_REPORTE      VARCHAR2(150) NOT NULL,
    DESCRIPCION         VARCHAR2(500),
    PROMPT_SISTEMA      CLOB NOT NULL,
    QUERY_BASE          CLOB NOT NULL,
    ESTADO              VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT PK_CATALOGO_REPORTES PRIMARY KEY (ID_REPORTE) USING INDEX TABLESPACE TS_DBTEST_IDX
) TABLESPACE TS_DBTEST_DAT;

COMMENT ON TABLE USR_DBTEST.CATALOGO_REPORTES IS 'Catálogo maestro de reportes analíticos estáticos con metadatos para la IA';
COMMENT ON COLUMN USR_DBTEST.CATALOGO_REPORTES.ID_REPORTE IS 'Identificador único del reporte (PK)';
COMMENT ON COLUMN USR_DBTEST.CATALOGO_REPORTES.CATEGORIA IS 'Categoría del reporte (ej. VENTAS, FINANZAS, OPERACIONES)';
COMMENT ON COLUMN USR_DBTEST.CATALOGO_REPORTES.NOMBRE_REPORTE IS 'Nombre descriptivo del reporte';
COMMENT ON COLUMN USR_DBTEST.CATALOGO_REPORTES.DESCRIPCION IS 'Descripción explicativa de la funcionalidad del reporte';
COMMENT ON COLUMN USR_DBTEST.CATALOGO_REPORTES.PROMPT_SISTEMA IS 'Estructura y reglas de contexto del esquema para Gemini AI';
COMMENT ON COLUMN USR_DBTEST.CATALOGO_REPORTES.QUERY_BASE IS 'Sentencia SQL base de soporte sobre V_VENTAS_DETALLADAS';
COMMENT ON COLUMN USR_DBTEST.CATALOGO_REPORTES.ESTADO IS 'Estado de disponibilidad: ACTIVO o INACTIVO';

-- 2. OTORGAR PERMISOS Y SINÓNIMOS A USR_DBTEST_APP

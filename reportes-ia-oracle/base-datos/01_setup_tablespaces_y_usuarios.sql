/* ==============================================================================
 * SCRIPT 01: Configuración de Tablespaces y Usuarios (Fase 1)
 * Proyecto: Motor Dinámico de Reportes Orientado a Prompts (Text-to-SQL)
 * ============================================================================== */

ALTER SESSION SET "_ORACLE_SCRIPT"=true;

-- 1. CREACIÓN DE TABLESPACES
-- Tablespace para metadatos del usuario Owner
CREATE SMALLFILE TABLESPACE TS_DBTEST_USER 
  DATAFILE '/opt/oracle/oradata/ORCLDBTEST/ORCLPDB1/TSDBTEST_USER.DBF' SIZE 10M AUTOEXTEND ON NEXT 1M;

-- Tablespace temporal
CREATE TEMPORARY TABLESPACE TS_DBTEST_TEMP 
  TEMPFILE '/opt/oracle/oradata/ORCLDBTEST/ORCLPDB1/TSDBTEST_TEMP.DBF' SIZE 5M AUTOEXTEND ON NEXT 1M;

-- Tablespace exclusivo para DATOS de Tablas
CREATE SMALLFILE TABLESPACE TS_DBTEST_DAT 
  DATAFILE '/opt/oracle/oradata/ORCLDBTEST/ORCLPDB1/TSDBTEST_DATA.DBF' SIZE 300M AUTOEXTEND ON NEXT 1M;

-- Tablespace exclusivo para ÍNDICES y Primary Keys
CREATE SMALLFILE TABLESPACE TS_DBTEST_IDX 
  DATAFILE '/opt/oracle/oradata/ORCLDBTEST/ORCLPDB1/TSDBTEST_INDX.DBF' SIZE 300M AUTOEXTEND ON NEXT 1M;

-- 2. CREACIÓN DE USUARIO OWNER DDL (USR_DBTEST)
CREATE USER USR_DBTEST 
  IDENTIFIED BY aldana29 
  DEFAULT TABLESPACE TS_DBTEST_USER 
  TEMPORARY TABLESPACE TS_DBTEST_TEMP 
  ACCOUNT UNLOCK;

-- Asignación de cuotas y roles de administración para el Owner
ALTER USER USR_DBTEST QUOTA UNLIMITED ON TS_DBTEST_USER;
ALTER USER USR_DBTEST QUOTA UNLIMITED ON TS_DBTEST_DAT;
ALTER USER USR_DBTEST QUOTA UNLIMITED ON TS_DBTEST_IDX;

GRANT CONNECT, RESOURCE, DBA TO USR_DBTEST WITH ADMIN OPTION;

-- 3. CREACIÓN DE USUARIO DE APLICACIÓN RUNTIME (USR_DBTEST_APP)
-- Usuario de menor privilegio para conexión JDBC desde el Backend Java 21
CREATE USER USR_DBTEST_APP 
  IDENTIFIED BY aldana29 
  DEFAULT TABLESPACE TS_DBTEST_USER 
  TEMPORARY TABLESPACE TS_DBTEST_TEMP 
  ACCOUNT UNLOCK;

GRANT CONNECT TO USR_DBTEST_APP;

-- El usuario USR_DBTEST_APP NO posee permisos de DDL ni DML destructivo (NO INSERT, NO UPDATE, NO DELETE, NO DROP)
